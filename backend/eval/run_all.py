import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from config import EVAL_DIR, MODEL_DIR, SUBSETS
from data import prepare

RMSE_MAX = {"FD001": 14, "FD002": 20, "FD003": 14, "FD004": 22}
COVERAGE = (0.85, 0.95)
LATENCY_MEDIAN_MAX = 5.0
LATENCY_P95_MAX = 10.0
MODELS = ["lgbm", "cnn", "lstm", "transformer", "ensemble"]


def load(name):
    return json.load(open(f"{MODEL_DIR}/results_{name}.json"))


def leakage():
    for s in SUBSETS:
        d = prepare(s)
        if set(np.unique(d["utr"])) & set(np.unique(d["uval"])):
            return False
    return True


def status(ok):
    return "PASS" if ok else "FAIL"


def main():
    res = {m: load(m) for m in MODELS}
    ens, dec, onnx = res["ensemble"], load("decision"), load("onnx")
    arch = ens["FD001"]["arch"]
    rows = []
    for s in SUBSETS:
        best = min(MODELS, key=lambda m: res[m][s]["rmse"])
        for m in MODELS:
            r = res[m][s]["rmse"]
            label = f"ensemble ({arch} x5)" if m == "ensemble" else m
            mark = " *" if m == best else ""
            st = "baseline" if m == "lgbm" else status(r <= RMSE_MAX[s])
            rows.append((f"RMSE {s} {label}{mark}", f"{r:.2f}", f"<= {RMSE_MAX[s]}", st))
    for s in SUBSETS:
        n, b = ens[s]["nasa"], res["lgbm"][s]["nasa"]
        rows.append((f"NASA score {s} ensemble", f"{n:.0f}", f"<= lgbm {b:.0f}", status(n <= b)))
    n = sum(ens[s]["n"] for s in SUBSETS)
    cov = sum(ens[s]["coverage"] * ens[s]["n"] for s in SUBSETS) / n
    rows.append(("90% interval coverage (all test engines)", f"{cov:.3f}", f"{COVERAGE[0]} to {COVERAGE[1]}",
                 status(COVERAGE[0] <= cov <= COVERAGE[1])))
    saving = dec["all"]["saving_vs_fixed"]
    rows.append(("Cost saving, predictive vs fixed schedule", f"{saving:.1f}%", "> 0%", status(saving > 0)))
    rows.append(("ONNX vs torch max abs diff", f"{max(onnx[s]['max_diff'] for s in SUBSETS):.5f}", "<= 0.01",
                 status(max(onnx[s]['max_diff'] for s in SUBSETS) <= 0.01)))
    rows.append(("ONNX latency median (ms)", f"{onnx['latency_median_ms']:.3f}", f"<= {LATENCY_MEDIAN_MAX}",
                 status(onnx["latency_median_ms"] <= LATENCY_MEDIAN_MAX)))
    rows.append(("ONNX latency p95 (ms)", f"{onnx['latency_p95_ms']:.3f}", f"<= {LATENCY_P95_MAX}",
                 status(onnx["latency_p95_ms"] <= LATENCY_P95_MAX)))
    clean = leakage()
    rows.append(("No unit leakage train/val", "none" if clean else "found", "none", status(clean)))

    w = [max(len(r[i]) for r in rows + [("metric", "result", "threshold", "status")]) for i in range(4)]
    line = lambda r: "  ".join(c.ljust(w[i]) for i, c in enumerate(r))
    print(line(("metric", "result", "threshold", "status")))
    print("  ".join("-" * x for x in w))
    for r in rows:
        print(line(r))
    fails = sum(r[3] == "FAIL" for r in rows)
    print(f"\n{sum(r[3] == 'PASS' for r in rows)} pass, {fails} fail, * = lowest test RMSE on that subset")
    write_md(rows, res, ens, dec, onnx, arch, cov)


def write_md(rows, res, ens, dec, onnx, arch, cov):
    out = ["# Results", "", "Generated by `python eval/run_all.py`. Test RMSE uses the last window of each test engine "
           "against RUL_FD00x.txt with the true RUL capped at 125 (same cap as training). The uncapped column scores "
           "against the raw file values.", "", "## Summary", "", "| metric | result | threshold | status |",
           "|---|---|---|---|"]
    out += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |" for r in rows]
    for s in SUBSETS:
        out += ["", f"## {s}", "", "| model | val RMSE | test RMSE | test RMSE uncapped | NASA score |", "|---|---|---|---|---|"]
        for m in MODELS:
            r = res[m][s]
            label = f"ensemble ({arch} x5)" if m == "ensemble" else m
            out.append(f"| {label} | {r['val_rmse']:.2f} | {r['rmse']:.2f} | {r['rmse_raw']:.2f} | {r['nasa']:.0f} |")
        e, d = ens[s], dec[s]
        out += ["", f"90% interval coverage {e['coverage']:.3f} over {e['n']} engines, mean width {e['width']:.1f} cycles.", "",
                f"Maintenance simulation on {d['engines']} test engines (fixed interval {d['interval']} cycles, picked on train lifetimes): "
                f"run to failure {d['run_to_failure']}, fixed {d['fixed']}, predictive {d['predictive']}, "
                f"saving vs fixed {d['saving_vs_fixed']:.1f}%. Failures fixed/predictive: {d['failures_fixed']}/{d['failures_pred']}."]
    a = dec["all"]
    out += ["", "## Fleet total", "", f"Run to failure {a['run_to_failure']}, fixed {a['fixed']}, predictive {a['predictive']}, "
            f"saving vs fixed {a['saving_vs_fixed']:.1f}%. Pooled 90% coverage {cov:.3f}.", "",
            f"ONNX ({arch} ensemble, 5 members in one graph), CPU, batch 1, {onnx['runs']} runs: median "
            f"{onnx['latency_median_ms']:.3f} ms, p95 {onnx['latency_p95_ms']:.3f} ms.", ""]
    with open(f"{EVAL_DIR}/results.md", "w") as f:
        f.write("\n".join(out))
    print(f"wrote {EVAL_DIR}/results.md")


if __name__ == "__main__":
    main()
